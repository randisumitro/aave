// Validation helper (used by tests and by the Creative Decision Engine)
export function validateEDL(edl: any): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  if (!edl || typeof edl !== "object") {
    errors.push("EDL must be an object");
    return { valid: false, errors };
  }

  if (edl.version !== "1.0.0") {
    errors.push('EDL version must be "1.0.0"');
  }

  if (!edl.project) {
    errors.push("EDL.project is required");
  } else {
    for (const field of ["format", "width", "height", "fps", "target_duration", "aspect_ratio"]) {
      if (!(field in edl.project)) {
        errors.push(`EDL.project.${field} is required`);
      }
    }
    if (edl.project.aspect_ratio && !["9:16", "1:1", "16:9"].includes(edl.project.aspect_ratio)) {
      errors.push('EDL.project.aspect_ratio must be one of "9:16", "1:1", "16:9"');
    }
  }

  if (!edl.creative_direction) {
    errors.push("EDL.creative_direction is required");
  } else {
    for (const field of ["style", "pace", "tone"]) {
      if (!(field in edl.creative_direction)) {
        errors.push(`EDL.creative_direction.${field} is required`);
      }
    }
  }

  if (!Array.isArray(edl.timeline) || edl.timeline.length === 0) {
    errors.push("EDL.timeline must be a non-empty array");
  } else {
    edl.timeline.forEach((entry: any, i: number) => {
      for (const field of ["id", "source", "source_in", "source_out", "timeline_start", "role", "duration"]) {
        if (!(field in entry)) {
          errors.push(`EDL.timeline[${i}].${field} is required`);
        }
      }
      if (entry.role && !["hook", "context", "b_roll", "ending"].includes(entry.role)) {
        errors.push(`EDL.timeline[${i}].role must be one of hook/context/b_roll/ending`);
      }
      if (entry.source_out !== undefined && entry.source_in !== undefined && entry.source_out <= entry.source_in) {
        errors.push(`EDL.timeline[${i}].source_out must be greater than source_in`);
      }
    });
  }

  return { valid: errors.length === 0, errors };
}

